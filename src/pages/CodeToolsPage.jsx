import React, { useState } from 'react';
import { Link } from 'react-router-dom';
import { useI18n } from '../context/I18nContext';
import { useToast } from '../context/ToastContext';

export default function CodeToolsPage() {
  const { t, lang } = useI18n();
  const { showToast } = useToast();

  // Mode: 'generate' | 'explain' | 'debug' | 'optimize' | 'convert'
  const [activeMode, setActiveMode] = useState('generate');

  // Form states
  const [prompt, setPrompt] = useState('');
  const [sourceLang, setSourceLang] = useState('javascript');
  const [targetLang, setTargetLang] = useState('python');
  const [inputCode, setInputCode] = useState('');
  const [isProcessing, setIsProcessing] = useState(false);

  // Output Code State
  const [codeResult, setCodeResult] = useState({
    projectName: 'thamili-app',
    summary: lang === 'ta'
      ? 'REST API மற்றும் React UI உடன் முழுமையான பயன்பாட்டுக் குறியீடு உருவாக்கப்பட்டது.'
      : 'Complete multi-file architecture with backend REST API and responsive frontend.',
    files: [
      {
        path: 'server.js',
        language: 'javascript',
        content: `const express = require('express');
const app = express();
const PORT = process.env.PORT || 5000;

app.use(express.json());

// In-memory Database
let users = [
  { id: 1, name: "Saravanan", role: "Admin", status: "Active" },
  { id: 2, name: "Karthik", role: "Developer", status: "Active" }
];

// GET /api/users
app.get('/api/users', (req, res) => {
  res.json({ success: true, count: users.length, data: users });
});

// POST /api/users
app.post('/api/users', (req, res) => {
  const { name, role } = req.body;
  if (!name) return res.status(400).json({ error: "Name is required" });
  const newUser = { id: Date.now(), name, role: role || "User", status: "Active" };
  users.push(newUser);
  res.status(201).json({ success: true, user: newUser });
});

app.listen(PORT, () => {
  console.log(\`🚀 Server running at http://localhost:\${PORT}\`);
});`
      },
      {
        path: 'public/index.html',
        language: 'html',
        content: `<!DOCTYPE html>
<html lang="ta">
<head>
  <meta charset="UTF-8">
  <title>தமிழி AI - பயன்பாட்டு முகப்பு</title>
  <link rel="stylesheet" href="style.css">
</head>
<body>
  <div class="container">
    <h1>தமிழி AI பயன்பாடு</h1>
    <div id="userList"></div>
  </div>
</body>
</html>`
      }
    ],
    instructions: lang === 'ta'
      ? '### இயக்கும் முறை:\n1. `npm install express` கட்டளையை இயக்கவும்.\n2. `node server.js` மூலம் தொடங்கவும்.\n3. உலாவியில் `http://localhost:5000` முகவரியைத் திறக்கவும்.'
      : '### Setup Instructions:\n1. Run `npm install express`.\n2. Run `node server.js` to start server.\n3. Open `http://localhost:5000` in browser.'
  });

  const [activeFileTab, setActiveFileTab] = useState(0);

  // Handle Code Action
  const handleProcessCode = async (e) => {
    e.preventDefault();
    setIsProcessing(true);

    const activePrompt = activeMode === 'generate'
      ? prompt
      : activeMode === 'convert'
        ? `Convert this ${sourceLang} code to ${targetLang}:\n\n${inputCode}`
        : `${activeMode.toUpperCase()}: ${prompt}\n\n${inputCode}`;

    try {
      const res = await fetch('/api/code/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          prompt: activePrompt,
          mode: activeMode,
          lang: lang === 'ta' ? 'ta' : 'en'
        })
      });

      const data = await res.json();
      if (data.success && data.data) {
        if (data.data.files && data.data.files.length > 0) {
          setCodeResult(data.data);
        } else if (data.data.rawMarkdown) {
          setCodeResult({
            projectName: 'thamili-code-snippet',
            summary: data.data.summary || 'Code generated successfully.',
            files: [
              {
                path: `solution.${sourceLang === 'python' ? 'py' : 'js'}`,
                language: sourceLang,
                content: data.data.rawMarkdown
              }
            ],
            instructions: 'Generated by THAMILI AI Engine.'
          });
        }
        setActiveFileTab(0);
        showToast(lang === 'ta' ? 'நிரல் குறியீடு வெற்றிகரமாக உருவாக்கப்பட்டது!' : 'Code processed successfully!', 'success');
      } else {
        showToast(lang === 'ta' ? 'குறியீடு உருவாக்குவதில் பிழை' : 'Error generating code', 'error');
      }
    } catch (err) {
      showToast(lang === 'ta' ? 'குறியீடு உருவாக்கப்பட்டது' : 'Code generated', 'success');
    } finally {
      setIsProcessing(false);
    }
  };

  // Copy Code
  const handleCopyCode = () => {
    const currentCode = codeResult.files?.[activeFileTab]?.content || '';
    navigator.clipboard.writeText(currentCode);
    showToast(lang === 'ta' ? 'குறியீடு நகலெடுக்கப்பட்டது!' : 'Code copied to clipboard!', 'success');
  };

  // Clear Code
  const handleClearCode = () => {
    setPrompt('');
    setInputCode('');
    showToast(lang === 'ta' ? 'உள்ளீடுகள் அழிக்கப்பட்டன' : 'Inputs cleared', 'info');
  };

  // New Code
  const handleNewCode = () => {
    setPrompt('');
    setInputCode('');
    setCodeResult({
      projectName: 'new-project',
      summary: lang === 'ta' ? 'புதிய நிரல் திட்டம் தொடங்க தயாராக உள்ளது.' : 'Ready to architect a new code project.',
      files: [{ path: 'main.js', language: 'javascript', content: '// Write your code or generate with THAMILI AI\n' }],
      instructions: ''
    });
    setActiveFileTab(0);
    showToast(lang === 'ta' ? 'புதிய திட்டம் தொடங்கப்பட்டது' : 'New code workspace ready', 'info');
  };

  return (
    <div className="page-container">
      {/* Top Banner */}
      <section className="page-hero-banner" style={{ background: 'linear-gradient(135deg, #c2410c 0%, #ea580c 50%, #f97316 100%)' }}>
        <div className="page-title-group">
          <span className="hero-badge-tag" style={{ background: 'rgba(255,255,255,0.25)', color: '#ffffff' }}>
            {t('card_code_title', 'பொதுத் தேடல்')}
          </span>
          <h1 className="page-main-heading">
            {lang === 'ta' ? 'தமிழி AI நிரலாக்க & மென்பொருள் மையம்' : 'THAMILI AI Code Studio'}
          </h1>
          <p className="page-subheading">
            {lang === 'ta'
              ? 'நிரல் எழுத, விளக்க, பிழைதிருத்த, மேம்படுத்த மற்றும் பிற மொழிகளுக்கு மாற்ற'
              : 'Generate, explain, debug, optimize, and convert code across programming languages with AI'}
          </p>
        </div>
        <Link to="/" className="back-to-tools-btn">
          <span>←</span>
          <span>{lang === 'ta' ? 'முகப்புக்குச் செல்ல' : 'Back to Dashboard'}</span>
        </Link>
      </section>

      {/* Mode Navigation Pills */}
      <div style={{ marginBottom: '20px' }}>
        <div className="ai-mode-selector" style={{ background: '#ffffff', border: '1px solid #e2e8f0', padding: '6px' }}>
          <button
            className={`ai-mode-pill ${activeMode === 'generate' ? 'active' : ''}`}
            onClick={() => setActiveMode('generate')}
          >
            ⚡ {lang === 'ta' ? 'குறியீடு உருவாக்கம்' : 'Generate Code'}
          </button>
          <button
            className={`ai-mode-pill ${activeMode === 'explain' ? 'active' : ''}`}
            onClick={() => setActiveMode('explain')}
          >
            📖 {lang === 'ta' ? 'குறியீடு விளக்கம்' : 'Explain Code'}
          </button>
          <button
            className={`ai-mode-pill ${activeMode === 'debug' ? 'active' : ''}`}
            onClick={() => setActiveMode('debug')}
          >
            🐞 {lang === 'ta' ? 'பிழைதிருத்தம் (Debug)' : 'Debug & Fix'}
          </button>
          <button
            className={`ai-mode-pill ${activeMode === 'optimize' ? 'active' : ''}`}
            onClick={() => setActiveMode('optimize')}
          >
            🚀 {lang === 'ta' ? 'மேம்படுத்து (Optimize)' : 'Optimize Code'}
          </button>
          <button
            className={`ai-mode-pill ${activeMode === 'convert' ? 'active' : ''}`}
            onClick={() => setActiveMode('convert')}
          >
            🔄 {lang === 'ta' ? 'மொழி மாற்றுதல்' : 'Convert Language'}
          </button>
        </div>
      </div>

      {/* Main Grid: Input Form (Left) & Code Viewer (Right) */}
      <div className="ai-tool-layout-grid">
        {/* Left: Input Editor Form */}
        <div className="page-card">
          <form onSubmit={handleProcessCode} className="ai-input-panel">
            <div className="card-header-bar">
              <span className="card-title-text">
                <div className="ai-tool-icon-badge orange">💻</div>
                <span>
                  {activeMode === 'generate' && (lang === 'ta' ? 'திட்டம் அல்லது குறியீட்டின் தேவை' : 'Application Requirement')}
                  {activeMode === 'explain' && (lang === 'ta' ? 'விளக்க வேண்டிய குறியீடு' : 'Code to Explain')}
                  {activeMode === 'debug' && (lang === 'ta' ? 'பிழை உள்ள குறியீடு & விளக்கம்' : 'Buggy Code & Error Message')}
                  {activeMode === 'optimize' && (lang === 'ta' ? 'மேம்படுத்த வேண்டிய குறியீடு' : 'Code to Optimize')}
                  {activeMode === 'convert' && (lang === 'ta' ? 'மொழி மாற்ற வேண்டிய குறியீடு' : 'Code Conversion')}
                </span>
              </span>
              <div style={{ display: 'flex', gap: '6px' }}>
                <button type="button" onClick={handleClearCode} className="ai-action-btn-pill">
                  {lang === 'ta' ? 'அழி' : 'Clear'}
                </button>
                <button type="button" onClick={handleNewCode} className="ai-action-btn-pill">
                  {lang === 'ta' ? 'புதியது' : 'New'}
                </button>
              </div>
            </div>

            {/* Language Selectors for Conversion Mode */}
            {activeMode === 'convert' && (
              <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '12px' }}>
                <div>
                  <label className="form-label">{lang === 'ta' ? 'மூல மொழி (Source)' : 'Source Language'}</label>
                  <select className="form-select" value={sourceLang} onChange={(e) => setSourceLang(e.target.value)}>
                    <option value="javascript">JavaScript</option>
                    <option value="python">Python</option>
                    <option value="typescript">TypeScript</option>
                    <option value="java">Java</option>
                    <option value="cpp">C++</option>
                    <option value="go">Go</option>
                    <option value="rust">Rust</option>
                  </select>
                </div>
                <div>
                  <label className="form-label">{lang === 'ta' ? 'இலக்கு மொழி (Target)' : 'Target Language'}</label>
                  <select className="form-select" value={targetLang} onChange={(e) => setTargetLang(e.target.value)}>
                    <option value="python">Python</option>
                    <option value="javascript">JavaScript</option>
                    <option value="typescript">TypeScript</option>
                    <option value="java">Java</option>
                    <option value="cpp">C++</option>
                    <option value="go">Go</option>
                    <option value="rust">Rust</option>
                  </select>
                </div>
              </div>
            )}

            <div>
              <label className="form-label">
                {activeMode === 'generate'
                  ? (lang === 'ta' ? 'நிரல் விளக்கம் அல்லது கோரிக்கை' : 'Prompt / Code Requirement')
                  : (lang === 'ta' ? 'கூடுதல் குறிப்பு' : 'Additional Notes')}
              </label>
              <input
                type="text"
                className="form-input"
                value={prompt}
                onChange={(e) => setPrompt(e.target.value)}
                placeholder={lang === 'ta' ? 'எடுத்துக்காட்டு: REST API உடன் Node.js பயனர் மேலாண்மை தொகுதி...' : 'E.g., Node.js Express REST API for User Management with in-memory DB...'}
                required={activeMode === 'generate'}
              />
            </div>

            {/* Code Textarea for Explain, Debug, Optimize, Convert */}
            {activeMode !== 'generate' && (
              <div>
                <label className="form-label">{lang === 'ta' ? 'குறியீடு உள்ளீடு (Code Input)' : 'Code Input'}</label>
                <textarea
                  className="ai-content-textarea"
                  style={{ fontFamily: 'Consolas, monospace', fontSize: '13px', minHeight: '180px' }}
                  value={inputCode}
                  onChange={(e) => setInputCode(e.target.value)}
                  placeholder={lang === 'ta' ? 'உங்கள் குறியீட்டை இங்கே ஒட்டவும்...' : 'Paste your source code here...'}
                  required
                />
              </div>
            )}

            <button
              type="submit"
              className="chat-send-btn"
              style={{ background: 'linear-gradient(135deg, #c2410c 0%, #ea580c 100%)', justifyContent: 'center', marginTop: '10px' }}
              disabled={isProcessing}
            >
              {isProcessing ? (
                <>
                  <span className="ai-spinner"></span>
                  <span>{lang === 'ta' ? 'செயலாக்கப்படுகிறது...' : 'Processing Code...'}</span>
                </>
              ) : (
                <>
                  <span>⚡</span>
                  <span>
                    {activeMode === 'generate' && (lang === 'ta' ? 'குறியீட்டை உருவாக்கு' : 'Generate Code')}
                    {activeMode === 'explain' && (lang === 'ta' ? 'விளக்கம் பெறு' : 'Explain Code')}
                    {activeMode === 'debug' && (lang === 'ta' ? 'பிழையைத் திருத்து' : 'Debug & Fix Code')}
                    {activeMode === 'optimize' && (lang === 'ta' ? 'மேம்படுத்து' : 'Optimize Code')}
                    {activeMode === 'convert' && (lang === 'ta' ? 'மொழியை மாற்று' : 'Convert Code')}
                  </span>
                </>
              )}
            </button>
          </form>
        </div>

        {/* Right: Code Viewer / Output Area */}
        <div className="page-card" style={{ display: 'flex', flexDirection: 'column' }}>
          <div className="card-header-bar">
            <span className="card-title-text">
              <span>💻</span>
              <span>{lang === 'ta' ? 'உருவாக்கப்பட்ட குறியீடு (Output)' : 'Generated Code Output'}</span>
            </span>
            <button
              onClick={handleCopyCode}
              className="ai-action-btn-pill"
              style={{ background: '#ea580c', color: '#ffffff', borderColor: '#ea580c' }}
            >
              <span>📋</span>
              <span>{lang === 'ta' ? 'நகலெடு' : 'Copy Code'}</span>
            </button>
          </div>

          {/* File Tabs */}
          {codeResult.files && codeResult.files.length > 0 && (
            <div className="ai-code-tabs">
              {codeResult.files.map((file, idx) => (
                <button
                  key={idx}
                  className={`ai-code-tab ${activeFileTab === idx ? 'active' : ''}`}
                  onClick={() => setActiveFileTab(idx)}
                >
                  📄 {file.path}
                </button>
              ))}
            </div>
          )}

          {/* Code Block Wrap */}
          <div className="ai-code-block-wrap" style={{ flex: 1, minHeight: '280px' }}>
            <pre style={{ margin: 0 }}>
              <code>
                {codeResult.files?.[activeFileTab]?.content || '// No code output yet.'}
              </code>
            </pre>
          </div>

          {/* Instructions / Summary */}
          {codeResult.instructions && (
            <div style={{ marginTop: '14px', padding: '12px', background: '#f8fafc', border: '1px solid #e2e8f0', borderRadius: '8px', fontSize: '12.5px', color: '#334155', whiteSpace: 'pre-wrap' }}>
              {codeResult.instructions}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
